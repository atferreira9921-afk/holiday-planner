export function getVisaRequirement(
  passportCountry: string,
  destinationCountry: string,
): VisaRequirement | null {
  const passport = passportCountry.toUpperCase();
  const destination = destinationCountry.toUpperCase();
  return VISA_REQUIREMENTS[passport]?.[destination] ?? null;
}

